"""Pushes the scholarship list into the dashboard page (platform/index.html, Scholarship tab).

New programmes are appended to the page's SCH array; programmes it already has only get the corrected deadline.
The generated block sits between the SCH-SYNC markers and is rewritten on every run.
"""
import json
import re

from .config import ROOT

PAGE = ROOT / "platform" / "index.html"
BLOCK = re.compile(r"/\*SCH-SYNC-START\*/.*?/\*SCH-SYNC-END\*/", re.S)


def _entry(s):
    return {"id": s["id"], "field": s["field"], "uni": s["uni"], "country": s["country"], "city": "—", "levels": s["levels"],
            "kind": s["name"], "support": s["support"], "deadline": s.get("deadline", ""),
            "dl_note": " ".join(x for x in (s.get("deadline_note", ""), s.get("note", "")) if x),
            "url": s.get("url", ""), "diff": 4, "ielts": 6.5, "extra": [], **({"status0": s["status0"]} if s.get("status0") else {})}


def sync(state):
    page = PAGE.read_text(encoding="utf-8")
    if not BLOCK.search(page):
        raise RuntimeError("SCH-SYNC markers not found in platform/index.html")
    entries = [_entry(s) for s in state["scholarships"].values() if s.get("status") != "skipped"]
    js = ("/*SCH-SYNC-START*/\n// generated by `python -m agent scholarship`; do not edit by hand\n"
          f"const SCH_SYNC = {json.dumps(entries, ensure_ascii=False, separators=(',', ':'))};\n"
          "SCH_SYNC.forEach(n => { const o = SCH.find(p => p.id === n.id); if (o) { o.deadline = n.deadline || o.deadline; o.dl_note = n.dl_note || o.dl_note; } else SCH.push(n); });\n"
          "/*SCH-SYNC-END*/")
    PAGE.write_text(BLOCK.sub(lambda m: js, page, count=1), encoding="utf-8")
    return len(entries)
