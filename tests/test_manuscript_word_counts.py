def test_pairwise_manuscript_overlap_below_3_percent():
    """For every pair of manuscripts, shared sentences (>8 words) must be <=3% of either"""
    # Load word counts
    word_counts_file = Path("/opt/cursor/artifacts/word-counts.json")
    with open(word_counts_file, "r") as f:
        results = json.load(f)
    
    def extract_sentences_gt8(doc_path):
        """Extract sentences with more than 8 words"""
        doc = Document(doc_path)
        sentences = []
        for para in doc.paragraphs:
            text = para.text.strip()
            if len(text) > 20:
                # Split by period, filter by >8 words, normalize
                sents = [
                    s.strip().lower()
                    for s in text.split('.')
                    if len(s.strip().split()) > 8
                ]
                sentences.extend(sents)
        return set(sentences)
    
    # Extract sentences from all manuscripts
    all_sentences = {}
    for key, info in results.items():
        all_sentences[key] = extract_sentences_gt8(Path(info["filename"]))
    
    # Check all pairs
    failures = []
    keys = list(results.keys())
    for i, key1 in enumerate(keys):
        for key2 in keys[i+1:]:
            sents1 = all_sentences[key1]
            sents2 = all_sentences[key2]
            
            shared = sents1 & sents2
            pct1 = (len(shared) / len(sents1) * 100) if sents1 else 0
            pct2 = (len(shared) / len(sents2) * 100) if sents2 else 0
            max_pct = max(pct1, pct2)
            
            name1 = results[key1]["venue_name"]
            name2 = results[key2]["venue_name"]
            
            if max_pct > 3.0:
                failures.append(
                    f"{name1} vs {name2}: {len(shared)} shared sentences "
                    f"({max_pct:.1f}% > 3.0% limit)"
                )
    
    assert not failures, f"Manuscript pairs exceed 3% overlap:\n" + "\n".join(failures)


def test_forbidden_keywords_not_in_wrong_manuscripts():
    """Forbidden keywords must not appear in wrong manuscripts (whole-word matches)"""
    import re
    
    # Load manuscripts
    word_counts_file = Path("/opt/cursor/artifacts/word-counts.json")
    with open(word_counts_file, "r") as f:
        results = json.load(f)
    
    # Define forbidden keywords per product (whole-word regex)
    forbidden_rules = {
        "applied_energy_elsevier": {  # iEMS - energy/carbon only
            "name": "iEMS",
            "forbidden": [
                r'\bUAV\b', r'\breconnaissance\b', r'\bSTM32H7\b',
                r'\breservoir\b', r'\bEOR\b',
                r'\bLarson-Miller\b', r'\bmethanol\b', r'\breformer\b'
            ]
        },
        "intellisys_2027_ml": {  # Mili - UAV only
            "name": "Mili",
            "forbidden": [
                r'\bLarson-Miller\b', r'\bcreep\b', r'\bmethanol\b', r'\breformer\b',
                r'\bolefin\b', r'\bPTA\b',
                r'\breservoir\b', r'\bEOR\b'
            ]
        },
        "global_energy_show_2027": {  # iEOR - reservoir only
            "name": "iEOR",
            "forbidden": [
                r'\bUAV\b', r'\bSTM32H7\b',
                r'\bLarson-Miller\b', r'\bcreep\b', r'\bmethanol\b', r'\breformer\b',
                r'\bolefin\b', r'\bPTA\b'
            ]
        },
        "eign_2027_gas": {  # Methanol - reformer/catalyst only
            "name": "Methanol",
            "forbidden": [
                r'\bUAV\b', r'\bSTM32H7\b',
                r'\breservoir\b', r'\bEOR\b',
                r'\bolefin\b', r'\bPTA\b'
            ]
        }
    }
    
    failures = []
    for key, rules in forbidden_rules.items():
        if key not in results:
            continue
        
        doc = Document(results[key]["filename"])
        text = " ".join(p.text for p in doc.paragraphs)
        
        found_keywords = []
        for pattern in rules["forbidden"]:
            if re.search(pattern, text, re.IGNORECASE):
                # Extract keyword from pattern
                keyword = pattern.replace(r'\b', '').replace('\\', '')
                found_keywords.append(keyword)
        
        if found_keywords:
            failures.append(
                f"{rules['name']} contains forbidden keywords: {', '.join(found_keywords)}"
            )
    
    assert not failures, f"Cross-product contamination detected:\n" + "\n".join(failures)


