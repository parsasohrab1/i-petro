#!/usr/bin/env python3
"""Inject window.REPO_SNAPSHOT — the inline snapshot of every repo-backed dashboard section —
into platform/index.html between the REPO_SNAPSHOT markers.

Method two (repo commits) must work even when the artifact cannot fetch /data/*.json and the
artifact database is empty: the snapshot travels INSIDE the artifact HTML, so updating the
artifact from platform/index.html carries the data with it — one file, guaranteed fresh.
scripts/dashboard_update.py regenerates the snapshot after every data change.

Trim policy: tender description/facts are capped (list-preview lengths) to keep the artifact
small; every other section is embedded verbatim.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HTML = ROOT / "platform" / "index.html"
BEGIN = "<!-- REPO_SNAPSHOT:BEGIN (generated by scripts/embed_dashboard_data.py — do not edit by hand) -->"
END = "<!-- REPO_SNAPSHOT:END -->"
TENDER_FIELDS = ["id", "source", "market", "title", "description", "buyer", "country", "deadline",
                 "deadline_fa", "published", "url", "notice_type", "sector", "facts", "domains",
                 "keyword_score", "line", "days_left", "setad_number", "status"]


def _load(rel, key=None, default=None):
    p = ROOT / rel
    if not p.exists():
        return default
    d = json.loads(p.read_text(encoding="utf-8"))
    return d if key is None else d.get(key, default)


def build():
    tenders = {}
    for tid, t in (_load("data/tenders.json", "tenders", {}) or {}).items():
        rec = {k: t.get(k) for k in TENDER_FIELDS}
        for k, cap in (("description", 400), ("facts", 200)):
            v = rec.get(k)
            if isinstance(v, str) and len(v) > cap:
                rec[k] = v[:cap] + "…"
        tenders[tid] = rec
    investors = {k: {kk: vv for kk, vv in (v or {}).items() if kk != "draft"}
                 for k, v in (_load("data/investors.json", "investors", {}) or {}).items()}
    seed = _load("platform/products_seed.json", default={}) or {}
    return {
        "tenders": tenders,
        "events": _load("data/events.json", "events", {}),
        "investors": investors,
        "leads": _load("data/leads.json", "leads", {}),
        "partners": _load("data/partners.json", "companies", {}),
        "requests": _load("requests_seed.json", "requests", []),
        "schol": _load("data/scholarships.json", "scholarships", {}),
        "calls": _load("data/papers.json", "calls", {}),
        "products": seed.get("products", []),
        "patents": seed.get("patents_from_repos", []),
        "art_registry": _load("data/articles_export/article_registry.json", default={"list": []}),
        "art_drafts": _load("data/article_drafts.json", default={"drafts": {}}),
    }


def inject(html, payload):
    """Insert (or replace) the snapshot block; it must run before the dashboard app script."""
    block = f"{BEGIN}\n<script>window.REPO_SNAPSHOT={payload};</script>\n{END}"
    if BEGIN in html:
        start = html.index(BEGIN)
        end = html.index(END, start) + len(END)
        return html[:start] + block + html[end:]
    i = html.index("<script>")   # first script block = the dashboard app; snapshot goes before it
    return html[:i] + block + "\n" + html[i:]


def main():
    payload = json.dumps(build(), ensure_ascii=False).replace("<", "\\u003c")   # </script>-safe inside a script block
    html = inject(HTML.read_text(encoding="utf-8"), payload)
    HTML.write_text(html, encoding="utf-8")
    print(f"[embed] REPO_SNAPSHOT rebuilt in {HTML.name}: {len(payload)} bytes of data, file now {len(html)} bytes")


if __name__ == "__main__":
    main()
